let language = "en";
let questionIndex = 0;
let selectedAnswer = null;
let answers = [];

const $ = (selector) => document.querySelector(selector);
const article = $("#article");
const quiz = $("#quiz");
const result = $("#result");
const quizContent = $("#quizContent");
const nextButton = $("#nextButton");

function setLanguage(lang) {
  language = lang;
  const t = translations[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "he" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) el.textContent = t[key];
  });
  document.querySelectorAll(".lang-btn").forEach((button) => {
    const active = button.dataset.lang === lang;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  if (!quiz.classList.contains("hidden")) renderQuestion();
  if (!result.classList.contains("hidden")) showResult();
}

function renderQuestion() {
  const t = translations[language];
  const item = t.questions[questionIndex];
  selectedAnswer = answers[questionIndex] ?? null;
  $("#questionCount").textContent = `${String(questionIndex + 1).padStart(2, "0")} / ${String(t.questions.length).padStart(2, "0")}`;
  $("#progressFill").style.width = `${((questionIndex + 1) / t.questions.length) * 100}%`;
  quizContent.innerHTML = "";
  const question = document.createElement("div");
  question.className = "question";
  question.textContent = `${questionIndex + 1}. ${item.q}`;
  const answersEl = document.createElement("div");
  answersEl.className = "answers";
  item.a.forEach((answer, i) => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = `answer${selectedAnswer === i ? " selected" : ""}`;
    button.setAttribute("aria-pressed", String(selectedAnswer === i));
    const letter = document.createElement("span");
    letter.className = "letter";
    letter.textContent = String.fromCharCode(65 + i);
    const text = document.createElement("span");
    text.textContent = answer;
    button.append(letter, text);
    button.addEventListener("click", () => {
      selectedAnswer = i;
      answers[questionIndex] = i;
      answersEl.querySelectorAll(".answer").forEach((el, index) => {
        const active = index === i;
        el.classList.toggle("selected", active);
        el.setAttribute("aria-pressed", String(active));
      });
      nextButton.disabled = false;
    });
    answersEl.appendChild(button);
  });
  quizContent.append(question, answersEl);
  nextButton.disabled = selectedAnswer === null;
  nextButton.querySelector("span").textContent = questionIndex === t.questions.length - 1 ? t.nextFinish : t.nextButton;
}

function beginQuiz() {
  article.classList.add("hidden");
  quiz.classList.remove("hidden");
  quiz.scrollIntoView({ behavior: "smooth", block: "start" });
  questionIndex = 0;
  answers = [];
  renderQuestion();
}

function showResult() {
  const t = translations[language];
  const correct = t.questions.reduce((total, q, i) => total + (answers[i] === q.c ? 1 : 0), 0);
  const score = Math.round((correct / t.questions.length) * 100);
  $("#scoreValue").textContent = score;
  const tier = score < 40 ? 0 : score < 70 ? 1 : score < 90 ? 2 : 3;
  $("#resultMessage").textContent = t.messages[tier];
}

function finishQuiz() {
  quiz.classList.add("hidden");
  result.classList.remove("hidden");
  showResult();
  result.scrollIntoView({ behavior: "smooth", block: "start" });
}

document.querySelectorAll(".lang-btn").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});
$("#readButton").addEventListener("click", beginQuiz);
nextButton.addEventListener("click", () => {
  if (selectedAnswer === null) return;
  if (questionIndex < translations[language].questions.length - 1) {
    questionIndex++;
    renderQuestion();
  } else {
    finishQuiz();
  }
});
$("#restartButton").addEventListener("click", () => {
  result.classList.add("hidden");
  article.classList.remove("hidden");
  quiz.classList.add("hidden");
  answers = [];
  questionIndex = 0;
  article.scrollIntoView({ behavior: "smooth", block: "start" });
});

setLanguage("en");
